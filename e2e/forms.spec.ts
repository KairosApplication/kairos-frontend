import { test, expect } from '@playwright/test'
import { mockSession } from './support'

test.beforeEach(async ({ page }) => { await mockSession(page) })

test('@a11y perfil usa a conta autenticada e identifica os dados em consulta', async ({ page }) => {
  await page.goto('/perfil')
  await expect(page.getByRole('heading', { name: 'gerente.acessibilidade@kairos.example' })).toBeVisible()
  const email = page.getByRole('textbox', { name: 'E-mail corporativo', exact: true })
  await email.focus()
  await expect(email).toBeFocused()
  await expect(email).toHaveValue('gerente.acessibilidade@kairos.example')
  await expect(email).toHaveAttribute('readonly', '')
  await expect(page.getByRole('textbox', { name: 'Nome completo', exact: true })).toHaveValue('')
  await expect(page.getByText('Ana Costa', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Salvar alterações' })).toHaveCount(0)
})

test('@a11y settings shows session data, readonly fields and persistent theme', async ({ page }) => {
  await page.goto('/configuracoes')
  await expect(page.getByRole('textbox', { name: 'Unidade', exact: true })).toHaveAttribute('readonly', '')
  await expect(page.getByRole('textbox', { name: 'E-mail da conta' })).toHaveValue('gerente.acessibilidade@kairos.example')
  await expect(page.getByRole('group', { name: 'Tema da interface' })).toBeVisible()
  await page.getByRole('button', { name: 'Escuro', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})

test('@a11y funcionário valida campos obrigatórios e permite cancelar pelo teclado', async ({ page }) => {
  await page.goto('/funcionarios')
  const trigger = page.getByRole('button', { name: 'Novo funcionário', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Novo funcionário', exact: true })
  await dialog.getByRole('button', { name: 'Salvar funcionário' }).click()
  const name = dialog.getByRole('textbox', { name: 'Nome completo' })
  await expect(name).toBeFocused()
  await expect(name).toHaveAccessibleDescription('Preencha este campo.')
  await name.fill('Outra pessoa')
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})
test('@a11y reposição identifica quantidade inválida e oferece correção', async ({ page }) => {
  await page.goto('/reposicoes')
  await page.getByRole('button', { name: 'Criar reposição', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Criar reposição', exact: true })
  for (const [label, value] of [['Produto', '1'], ['Gôndola', '101'], ['Responsável', '1'], ['Depósito', '1']]) await dialog.getByRole('combobox', { name: label, exact: true }).selectOption(value)
  const quantity = dialog.getByRole('spinbutton', { name: 'Quantidade' })
  await quantity.fill('0')
  await dialog.getByRole('button', { name: 'Salvar reposição' }).click()
  await expect(quantity).toBeFocused()
  await expect(quantity).toHaveAccessibleDescription('Informe um valor de pelo menos 1.')
  await quantity.fill('12')
  await dialog.getByRole('button', { name: 'Salvar reposição' }).click()
  await expect(page.getByText('Registro de reposição atualizado.', { exact: true })).toBeVisible()
})
