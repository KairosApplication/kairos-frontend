import { test, expect } from '@playwright/test'
import { mockSession } from './support'

test.beforeEach(async ({ page }) => { await mockSession(page) })

test('@a11y perfil associa erro e preserva foco durante correção; sucesso pode ser repetido', async ({ page }) => {
  await page.goto('/perfil')
  const name = page.getByRole('textbox', { name: 'Nome completo', exact: true })
  await name.fill('   ')
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(name).toBeFocused()
  await expect(name).toHaveAttribute('aria-invalid', 'true')
  await expect(name).toHaveAccessibleDescription('Preencha este campo.')
  await name.fill('Ana Acessível')
  await expect(name).toBeFocused()
  await expect(name).not.toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  const status = page.getByRole('status', { name: 'Resultado da operação' })
  await expect(status).toContainText('Sua conta real não foi alterada')
  await status.evaluate(element => { const child = element.firstElementChild; const observer = new MutationObserver(() => { if (element.firstElementChild !== child) element.setAttribute('data-updated', 'true') }); observer.observe(element, { childList: true }) })
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(status).toHaveAttribute('data-updated', 'true')
})

test('@a11y configurações identifica unidade e e-mail inválidos e nomeia o grupo de tema', async ({ page }) => {
  await page.goto('/configuracoes')
  const unit = page.getByRole('textbox', { name: 'Unidade', exact: true })
  await unit.fill(' ')
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(unit).toBeFocused()
  await expect(unit).toHaveAccessibleDescription('Preencha este campo.')
  await unit.fill('Centro')
  const email = page.getByRole('textbox', { name: 'E-mail de contato' })
  await email.fill('invalido')
  await page.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(email).toBeFocused()
  await expect(email).toHaveAccessibleDescription('Informe um e-mail válido.')
  await expect(page.getByRole('group', { name: 'Tema', exact: true })).toBeVisible()
})

test('@a11y funcionário informa e-mail duplicado no campo e permite cancelar pelo teclado', async ({ page }) => {
  await page.goto('/funcionarios')
  const trigger = page.getByRole('button', { name: 'Novo funcionário', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Novo funcionário', exact: true })
  await dialog.getByRole('textbox', { name: 'Nome completo' }).fill('Outra pessoa')
  const email = dialog.getByRole('textbox', { name: 'E-mail', exact: true })
  await email.fill('joao@kairos.example')
  await dialog.getByRole('button', { name: 'Adicionar à demonstração' }).click()
  await expect(email).toBeFocused()
  await expect(email).toHaveAccessibleDescription('Este e-mail já está na demonstração.')
  await email.fill('novo@kairos.example')
  await expect(email).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('@a11y reposição identifica quantidade inválida e oferece correção', async ({ page }) => {
  await page.goto('/reposicoes')
  await page.getByRole('button', { name: 'Criar reposição', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Criar reposição', exact: true })
  await dialog.getByRole('textbox', { name: 'Produto', exact: true }).fill('Produto de teste')
  await dialog.getByRole('textbox', { name: 'Gôndola', exact: true }).fill('A12')
  const quantity = dialog.getByRole('spinbutton', { name: 'Quantidade' })
  await quantity.fill('0')
  await dialog.getByRole('button', { name: 'Adicionar à demonstração' }).click()
  await expect(quantity).toBeFocused()
  await expect(quantity).toHaveAccessibleDescription('Informe um valor de pelo menos 1.')
  await quantity.fill('12')
  await dialog.getByRole('button', { name: 'Adicionar à demonstração' }).click()
  await expect(page.getByRole('status', { name: 'Resultado da operação' })).toContainText('Reposição adicionada')
})
